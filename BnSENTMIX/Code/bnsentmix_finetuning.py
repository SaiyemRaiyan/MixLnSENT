"""## 14. Soft-Voting Ensemble (BanglaBERT + XLM-RoBERTa + BanglishBERT)
Voting weights are grid-searched on the **validation set only**; the test set is consider exactly once, for the final reported ensemble score.
"""

def get_probs(model, tokenizer, ds):
    tok = tokenize_ds(ds, tokenizer)
    cols = [c for c in ["input_ids", "attention_mask", "token_type_ids"] if c in tok.column_names]
    tok.set_format(type="torch", columns=cols)
    loader = torch.utils.data.DataLoader(tok, batch_size=32)
    model.eval()
    probs = []
    with torch.no_grad():
        for batch in loader:
            batch = {k: v.to(DEVICE) for k, v in batch.items()}
            logits = model(**batch).logits
            probs.append(F.softmax(logits, dim=-1).cpu().numpy())
    return np.concatenate(probs, axis=0)

names = list(ensemble_assets.keys())
val_probs = {n: get_probs(m, tok, val_ds) for n, (m, tok) in ensemble_assets.items()}
test_probs = {n: get_probs(m, tok, test_ds) for n, (m, tok) in ensemble_assets.items()}
val_labels = np.array(val_ds["label"])
test_labels = np.array(test_ds["label"])

def macro_f1_from_probs(weighted_probs, y_true):
    preds = np.argmax(weighted_probs, axis=-1)
    return precision_recall_fscore_support(y_true, preds, average="macro", zero_division=0)[2]

weight_grid = np.round(np.arange(0.0, 1.05, 0.1), 2)
best_w, best_val_f1 = None, -1
for w1 in weight_grid:
    for w2 in weight_grid:
        w3 = round(1 - w1 - w2, 2)
        if w3 < 0 or w3 > 1:
            continue
        weighted = w1 * val_probs[names[0]] + w2 * val_probs[names[1]] + w3 * val_probs[names[2]]
        f1 = macro_f1_from_probs(weighted, val_labels)
        if f1 > best_val_f1:
            best_val_f1 = f1
            best_w = (w1, w2, w3)

weight_dict = dict(zip(names, best_w))
print(f"Best weights (validation macro-F1={best_val_f1:.4f}):", weight_dict)
log_experiment("Ensemble(BanglaBERT+XLM-R+BanglishBERT)", "weight_search", SEED,
                {"weight_grid_step": 0.1}, {"val_macro_f1": best_val_f1, "weights": weight_dict})

w1, w2, w3 = best_w
ensemble_test_probs = w1 * test_probs[names[0]] + w2 * test_probs[names[1]] + w3 * test_probs[names[2]]
ensemble_preds = np.argmax(ensemble_test_probs, axis=-1)

acc = accuracy_score(test_labels, ensemble_preds)
p_w, r_w, f1_w, _ = precision_recall_fscore_support(test_labels, ensemble_preds, average="weighted", zero_division=0)
p_m, r_m, f1_m, _ = precision_recall_fscore_support(test_labels, ensemble_preds, average="macro", zero_division=0)

ensemble_result = {"model": "Soft-Voting Ensemble", "weights": weight_dict, "accuracy": acc,
                    "precision": p_w, "recall": r_w, "f1": f1_w,
                    "precision_macro": p_m, "recall_macro": r_m, "f1_macro": f1_m}
log_experiment("Ensemble(BanglaBERT+XLM-R+BanglishBERT)", "soft_voting_test", SEED,
                {"weights": weight_dict}, ensemble_result)

print(ensemble_result)

best_single = tuned_single_df.iloc[0]
print(f"\nBest single tuned model: {best_single['model']} | macro-F1={best_single['f1_macro']:.4f}")
print(f"Soft-voting ensemble:    macro-F1={f1_m:.4f}")
print(f"Improvement over best single model: {f1_m - best_single['f1_macro']:+.4f}")

