"""## 8b. SetFit: Contrastive Few-Shot Learning
SetFit (Tunstall et al., 2022) is the established approach for N<50 examples/class: it fine-tunes a Sentence-Transformer body on contrastive pairs generated from the few-shot examples, then fits a lightweight classification head, without any prompt or large-scale generative model. It typically
outperforms standard cross-entropy fine-tuning of a full transformer at this data scale.
"""

import wandb

wandb.login()

from setfit import (
    SetFitModel,
    Trainer as SFTrainer,
    TrainingArguments as SFTrainingArguments
)

SETFIT_BASE = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"


def run_setfit(
    shot_df,
    test_df,
    seed,
    setting,
    num_iterations=20,
    epochs=1
):
    set_seed(seed)

    model = SetFitModel.from_pretrained(SETFIT_BASE)

    train_dataset = Dataset.from_pandas(
        shot_df[["text", "label"]].reset_index(drop=True),
        preserve_index=False
    )

    args = SFTrainingArguments(
        batch_size=16,
        num_epochs=epochs,
        num_iterations=num_iterations,
        seed=seed,

        # Already logged in -> no API key code needed
        report_to="wandb",
        run_name=f"SetFit-{setting}-seed-{seed}",

        save_strategy="no"
    )

    trainer = SFTrainer(
        model=model,
        args=args,
        train_dataset=train_dataset,
        metric="accuracy"
    )

    trainer.train()

    # Prediction
    y_pred = np.asarray(
        model.predict(test_df["text"].tolist())
    )

    y_true = test_df["label"].to_numpy()

    # Metrics
    acc = accuracy_score(y_true, y_pred)

    p_w, r_w, f1_w, _ = precision_recall_fscore_support(
        y_true,
        y_pred,
        average="weighted",
        zero_division=0
    )

    p_m, r_m, f1_m, _ = precision_recall_fscore_support(
        y_true,
        y_pred,
        average="macro",
        zero_division=0
    )

    m = {
        "eval_accuracy": acc,
        "eval_precision": p_w,
        "eval_recall": r_w,
        "eval_f1": f1_w,
        "eval_precision_macro": p_m,
        "eval_recall_macro": r_m,
        "eval_f1_macro": f1_m
    }

    # Cleanup
    del trainer
    del model

    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    return m, (y_true, y_pred)


